"""Generate the UAX #31 XID_Start / XID_Continue tables for identifier.cpp.

Python's str.isidentifier() is defined by XID_Start/XID_Continue (plus the
underscore), so the tables follow the Unicode version of the interpreter:

  XID_Start(c)    = chr(c).isidentifier() and c != '_'
  XID_Continue(c) = ('a' + chr(c)).isidentifier()

Each range is packed into one uint32: start << 11 | (length - 1). Ranges
longer than 2048 code points are split, so entries stay sorted by start and
can be binary-searched by `entry >> 11`.

    python3 tools/gen_xid_tables.py > components/a2ui_core/src/common/xid_tables.inc
"""

import sys
import unicodedata

MAX_LEN = 1 << 11


def ranges(pred):
  out = []
  start = None
  for c in range(0x110000 + 1):
    ok = c <= 0x10FFFF and not (0xD800 <= c <= 0xDFFF) and pred(c)
    if ok and start is None:
      start = c
    elif not ok and start is not None:
      out.append((start, c - 1))
      start = None
  return out


def packed(rs):
  out = []
  for lo, hi in rs:
    while lo <= hi:
      n = min(hi - lo + 1, MAX_LEN)
      out.append((lo << 11) | (n - 1))
      lo += n
  return out


def emit(name, entries, out):
  out.write(f"static const uint32_t {name}[{len(entries)}] = {{\n")
  for i in range(0, len(entries), 6):
    row = ", ".join(f"0x{e:08X}u" for e in entries[i:i + 6])
    out.write(f"    {row},\n")
  out.write("};\n\n")


def main():
  start = packed(ranges(lambda c: c != 0x5F and chr(c).isidentifier()))
  cont = packed(ranges(lambda c: ("a" + chr(c)).isidentifier()))
  out = sys.stdout
  out.write("// Copyright 2026 The a2ui-lvgl Authors\n")
  out.write("// SPDX-License-Identifier: Apache-2.0\n//\n")
  out.write("// Generated by tools/gen_xid_tables.py from Unicode "
            f"{unicodedata.unidata_version}. Do not edit.\n")
  out.write("// Entry = start << 11 | (length - 1), sorted by start.\n\n")
  emit("kXidStart", start, out)
  emit("kXidContinue", cont, out)


if __name__ == "__main__":
  main()
