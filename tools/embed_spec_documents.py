"""Generates the embedded specification documents of a2ui_core.

- components/a2ui_core/src/schema/spec_documents_data.cpp: the upstream v1.0
  specification documents the core validates against, minified, as C++
  string literals in flash (spec::text, spec::parsed).
- components/a2ui_core/src/schema/packed_documents_data.cpp: the same
  documents as constant PackedDocument tables (a2ui/schema_node.h), which
  the validator reads in place without using the heap (spec::packed, the
  compact catalog). The layout matches PackedBuffer in schema_node.cpp.

Run after updating the third_party/a2ui submodule:

    python3 tools/embed_spec_documents.py
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UPSTREAM = os.path.join(ROOT, "third_party", "a2ui")
SCHEMA_SRC = os.path.join(ROOT, "components", "a2ui_core", "src", "schema")
OUT = os.path.join(SCHEMA_SRC, "spec_documents_data.cpp")
PACKED_OUT = os.path.join(SCHEMA_SRC, "packed_documents_data.cpp")

DOCUMENTS = [
    ("kCommonTypesV1_0", "specification/v1_0/json/common_types.json"),
    ("kAgentToRendererV1_0", "specification/v1_0/json/agent_to_renderer.json"),
    ("kBasicCatalogV1", "catalogs/basic/v1/catalog.json"),
]

CHUNK = 2000
DELIM = "a2ui_json"

HEADER = [
    "// Copyright 2026 The a2ui-lvgl Authors",
    "// SPDX-License-Identifier: Apache-2.0",
    "//",
    "// GENERATED by tools/embed_spec_documents.py from third_party/a2ui. Do not edit.",
    "",
    '#include "spec_documents_data.h"',
    "",
    "namespace a2ui {",
    "namespace spec_data {",
    "",
]


def literal(text: str) -> str:
    if ")" + DELIM + '"' in text:
        sys.exit("document contains the raw string delimiter")
    parts = [text[i : i + CHUNK] for i in range(0, len(text), CHUNK)]
    return "\n".join(f'    R"{DELIM}({p}){DELIM}"' for p in parts)


# --- packed documents ---------------------------------------------------------

# Json::Type values (a2ui/json.h).
T_NULL, T_BOOL, T_NUMBER, T_STRING, T_ARRAY, T_OBJECT = 1, 2, 3, 4, 5, 6


class Members(list):
    """An object's (key, value) pairs in document order."""


def members(pairs):
    keys = [k for k, _ in pairs]
    if len(keys) != len(set(keys)):
        sys.exit("document has a duplicate object key")
    return Members(pairs)


class Pool:
    """String pool and number table shared by every packed document."""

    def __init__(self) -> None:
        self.data = bytearray()
        self.offsets = {}
        self.numbers = []
        self.number_index = {}

    def string(self, s: str):
        b = s.encode("utf-8")
        if b not in self.offsets:
            self.offsets[b] = len(self.data)
            self.data += b
        return len(b), self.offsets[b]

    def number(self, x) -> int:
        key = repr(float(x))
        if key not in self.number_index:
            self.number_index[key] = len(self.numbers)
            self.numbers.append(float(x))
        return self.number_index[key]


def pack(doc, pool: Pool) -> list:
    """Breadth-first node table, two words per node (see schema_node.h)."""
    nodes = [[0, 0]]
    queue = [(0, doc)]
    q = 0
    while q < len(queue):
        index, v = queue[q]
        q += 1
        nxt = len(nodes)
        if v is None:
            nodes[index] = [T_NULL, 0]
        elif isinstance(v, bool):
            nodes[index] = [T_BOOL | (int(v) << 3), 0]
        elif isinstance(v, (int, float)):
            nodes[index] = [T_NUMBER, pool.number(v)]
        elif isinstance(v, str):
            n, off = pool.string(v)
            nodes[index] = [T_STRING | (n << 3), off]
        elif isinstance(v, Members):
            nodes[index] = [T_OBJECT | (len(v) << 3), nxt]
            nodes.extend([0, 0] for _ in range(2 * len(v)))
            for i, (k, val) in enumerate(v):
                n, off = pool.string(k)
                nodes[nxt + 2 * i] = [T_STRING | (n << 3), off]
                queue.append((nxt + 2 * i + 1, val))
        else:
            nodes[index] = [T_ARRAY | (len(v) << 3), nxt]
            nodes.extend([0, 0] for _ in v)
            for i, e in enumerate(v):
                queue.append((nxt + i, e))
    return nodes


def c_bytes(data: bytes) -> str:
    """The pool as adjacent string literals; octal escapes for anything unusual."""
    lines, cur = [], ""
    for b in data:
        c = chr(b)
        if c in ('\\', '"', '?') or b < 0x20 or b >= 0x7F:
            cur += "\\%03o" % b
        else:
            cur += c
        if len(cur) >= 96:
            lines.append(f'    "{cur}"')
            cur = ""
    if cur or not lines:
        lines.append(f'    "{cur}"')
    return "\n".join(lines)


def write_packed(docs: list) -> None:
    pool = Pool()
    tables = [(name, rel, pack(doc, pool)) for name, rel, doc in docs]
    out = HEADER[:-1] + [
        "namespace {",
        "",
        f"// {len(pool.data)} bytes of strings, shared by the documents below.",
        "const char kStrings[] =",
        c_bytes(bytes(pool.data)) + ";",
        "",
        "const double kNumbers[] = {",
    ]
    out += [f"    {repr(x)}," for x in pool.numbers] or ["    0,"]
    out += ["};", ""]
    for name, rel, nodes in tables:
        out.append(f"// {rel}: {len(nodes)} nodes")
        out.append(f"const uint32_t {name}Nodes[] = {{")
        flat = [w for node in nodes for w in node]
        for i in range(0, len(flat), 8):
            out.append("    " + " ".join(f"{w}u," for w in flat[i : i + 8]))
        out += ["};", ""]
    out += ["}  // namespace", ""]
    for name, _, nodes in tables:
        out.append(f"const PackedDocument {name}Packed = {{{name}Nodes, kStrings, kNumbers, {len(nodes)}}};")
    out += ["", "}  // namespace spec_data", "}  // namespace a2ui", ""]
    with open(PACKED_OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))


def main() -> None:
    out = list(HEADER)
    packed = []
    for name, rel in DOCUMENTS:
        with open(os.path.join(UPSTREAM, rel), encoding="utf-8") as f:
            raw = f.read()
        doc = json.loads(raw)
        packed.append((name, rel, json.loads(raw, object_pairs_hook=members)))
        text = json.dumps(doc, separators=(",", ":"), ensure_ascii=False)
        out.append(f"// {rel}")
        out.append(f"const char {name}[] =")
        out.append(literal(text) + ";")
        out.append(f"const size_t {name}Size = sizeof({name}) - 1;")
        out.append("")
    out += ["}  // namespace spec_data", "}  // namespace a2ui", ""]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    write_packed(packed)


if __name__ == "__main__":
    main()
