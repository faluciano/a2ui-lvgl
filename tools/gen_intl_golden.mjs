// Generates test/unit/locale_intl_golden.inc: what the TypeScript SDK's
// formatters (Intl in Node with full ICU) produce for a grid of inputs, so
// the C++ formatters can be checked against the reference engine.
//
//   node tools/gen_intl_golden.mjs > test/unit/locale_intl_golden.inc

const LOCALES = ['en', 'en-US', 'en-GB', 'de', 'fr', 'es', 'it', 'pt', 'pt-BR', 'nl', 'sv',
  'ja', 'zh', 'ko', 'ru', 'pl', 'ar'];

function cstr(s) {
  let out = '"';
  for (const b of Buffer.from(s, 'utf8')) {
    if (b >= 0x20 && b < 0x7f && b !== 0x22 && b !== 0x5c && b !== 0x3f) out += String.fromCharCode(b);
    else out += '\\' + b.toString(8).padStart(3, '0');
  }
  return out + '"';
}

function cnum(v) {
  if (v === Infinity) return 'INFINITY';
  if (v === -Infinity) return '-INFINITY';
  if (Object.is(v, -0)) return '-0.0';
  return String(v).includes('e') || String(v).includes('.') ? String(v) : String(v) + '.0';
}

const lines = [];
lines.push(`// GENERATED by tools/gen_intl_golden.mjs with Node ${process.version}, ICU ${process.versions.icu}, CLDR ${process.versions.cldr}. Do not edit.`);

// formatNumber: {locale, value, decimals (-1 = absent), grouping (-1 absent, 0, 1), expected}
const numbers = [0, -0, 1, -1, 0.5, 1.5, 2.5, -2.5, 0.0005, 1.0005, 1.005, 12.3456, 999.9995,
  1234, 1234.5, -1234.5, 12345.678, -12345.678, 1234567.891, 0.1 + 0.2, 1e21,
  123456789012345680000, 1e-7, -0.0004, 9.995, Infinity, -Infinity];
lines.push('#ifdef GOLDEN_NUMBER');
for (const locale of LOCALES) {
  for (const value of numbers) {
    for (const [decimals, grouping] of [[-1, -1], [0, -1], [2, -1], [-1, 1], [-1, 0], [2, 0]]) {
      const opts = {};
      if (decimals >= 0) Object.assign(opts, {minimumFractionDigits: decimals, maximumFractionDigits: decimals});
      if (grouping >= 0) opts.useGrouping = grouping === 1;
      const out = new Intl.NumberFormat(locale, opts).format(value);
      lines.push(`GOLDEN_NUMBER(${cstr(locale)}, ${cnum(value)}, ${decimals}, ${grouping}, ${cstr(out)})`);
    }
  }
}
lines.push('#endif');

// formatCurrency: decimals defaults to 2 in the SDKs, so it is always passed.
const currencies = ['USD', 'EUR', 'GBP', 'JPY', 'CHF', 'SEK', 'CNY', 'KRW', 'RUB', 'PLN', 'BRL', 'INR',
  'CAD', 'AUD', 'HKD', 'MXN', 'KWD', 'XYZ', 'usd'];
const amounts = [1234.56, -1234.56, 0, -0.001, 12345];
lines.push('#ifdef GOLDEN_CURRENCY');
for (const locale of LOCALES) {
  for (const currency of currencies) {
    for (const value of amounts) {
      const variants = value === 1234.56 ? [[2, -1], [0, -1], [2, 0]] : [[2, -1]];
      for (const [decimals, grouping] of variants) {
        const opts = {style: 'currency', currency: currency.toUpperCase(),
          minimumFractionDigits: decimals, maximumFractionDigits: decimals};
        if (grouping >= 0) opts.useGrouping = grouping === 1;
        const out = new Intl.NumberFormat(locale, opts).format(value);
        lines.push(`GOLDEN_CURRENCY(${cstr(locale)}, ${cstr(currency)}, ${cnum(value)}, ${decimals}, ${grouping}, ${cstr(out)})`);
      }
    }
  }
}
lines.push('#endif');

// pluralize: Intl.PluralRules.select.
const plurals = [0, 1, 2, 3, 4, 5, 6, 7, 10, 11, 12, 14, 19, 21, 22, 25, 100, 101, 102, 103, 111,
  112, 1000, 1000000, 2000000, 1000001, 0.5, 1.5, 1.0004, 2.5, 0.1, 3.25, -1, -2, 1e21];
lines.push('#ifdef GOLDEN_PLURAL');
for (const locale of LOCALES) {
  const rules = new Intl.PluralRules(locale);
  for (const value of plurals) {
    lines.push(`GOLDEN_PLURAL(${cstr(locale)}, ${cnum(value)}, ${cstr(rules.select(value))})`);
  }
}
lines.push('#endif');

// Month and weekday names in format context (MMMM, MMM, EEEE, E), read from
// date-time patterns that put the field next to a day number.
lines.push('#ifdef GOLDEN_NAMES');
const part = (locale, options, date, type) =>
  new Intl.DateTimeFormat(locale, {...options, timeZone: 'UTC'}).formatToParts(date)
    .find(p => p.type === type).value;
for (const locale of LOCALES) {
  for (let m = 0; m < 12; ++m) {
    const date = new Date(Date.UTC(2021, m, 15));
    const iso = date.toISOString().slice(0, 10);
    // ja/zh/ko date patterns spell months numerically ("1月15日"), so the
    // month part there is a number, not the name.
    if (!['ja', 'zh', 'ko'].includes(locale)) {
      lines.push(`GOLDEN_NAMES(${cstr(locale)}, ${cstr(iso)}, "MMMM", ${cstr(part(locale, {month: 'long', day: 'numeric'}, date, 'month'))})`);
      lines.push(`GOLDEN_NAMES(${cstr(locale)}, ${cstr(iso)}, "MMM", ${cstr(part(locale, {month: 'short', day: 'numeric'}, date, 'month'))})`);
      lines.push(`GOLDEN_NAMES(${cstr(locale)}, ${cstr(iso)}, "LLLL", ${cstr(part(locale, {month: 'long'}, date, 'month'))})`);
    }
  }
  for (let d = 0; d < 7; ++d) {
    const date = new Date(Date.UTC(2021, 2, 7 + d));  // 2021-03-07 was a Sunday.
    const iso = date.toISOString().slice(0, 10);
    lines.push(`GOLDEN_NAMES(${cstr(locale)}, ${cstr(iso)}, "EEEE", ${cstr(part(locale, {weekday: 'long', day: 'numeric'}, date, 'weekday'))})`);
    lines.push(`GOLDEN_NAMES(${cstr(locale)}, ${cstr(iso)}, "E", ${cstr(part(locale, {weekday: 'short', day: 'numeric'}, date, 'weekday'))})`);
  }
}
lines.push('#endif');

console.log(lines.join('\n'));
